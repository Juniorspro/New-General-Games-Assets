// Las tildes: dos filas arriba (la de abajo toca la letra).
const MARCAS = {
  agudo: ['...#.', '..#..'], grave: ['.#...', '..#..'], circun: ['..#..', '.#.#.'],
  tilde: ['.##.#', '#..#.'], dieresis: ['.....', '.#.#.'],
};
const ACENTOS = {
  Á: ['A', 'agudo'], É: ['E', 'agudo'], Í: ['I', 'agudo'], Ó: ['O', 'agudo'], Ú: ['U', 'agudo'],
  À: ['A', 'grave'], Â: ['A', 'circun'], Ê: ['E', 'circun'], Ô: ['O', 'circun'],
  Ã: ['A', 'tilde'], Õ: ['O', 'tilde'], Ñ: ['N', 'tilde'], Ü: ['U', 'dieresis'],
};

export const ALTO = 10;    // un renglón: 2 de tilde + 7 de letra + 1 de aire

function glifo(c) {
  if (G[c]) return { filas: G[c], marca: null, cedilla: false };
  if (ACENTOS[c]) return { filas: G[ACENTOS[c][0]], marca: MARCAS[ACENTOS[c][1]], cedilla: false };
  if (c === 'Ç') return { filas: G.C, marca: null, cedilla: true };
  return { filas: G['?'], marca: null, cedilla: false };
}

// ¿La letra tiene dibujo? (la prueba de los textos lo usa)
export const soporta = (c) => !!(G[c] || ACENTOS[c] || c === 'Ç');

export function anchoTexto(texto, esc = 1) {
  let w = 0;
  for (const c of texto.toUpperCase()) w += (glifo(c).filas[0].length + 1) * esc;
  return Math.max(0, w - esc);
}

// Dibuja texto con cuadraditos. `sombra` es un color para una copia corrida
// 1 px abajo (el relieve de los carteles); `borde` lo rodea entero.
export function texto(g, txt, x, y, color, { esc = 1, sombra = null, borde = null, alinear = 'izq' } = {}) {
  txt = String(txt).toUpperCase();
  const w = anchoTexto(txt, esc);
  let x0 = Math.round(alinear === 'centro' ? x - w / 2 : alinear === 'der' ? x - w : x);
  const y0 = Math.round(y);
  const pintar = (col, ox, oy) => {
    g.fillStyle = col;
    let cx = x0 + ox;
    for (const c of txt) {
      const { filas, marca, cedilla } = glifo(c);
      for (let f = 0; f < 7; f++) for (let k = 0; k < filas[f].length; k++) if (filas[f][k] === '#') g.fillRect(cx + k * esc, y0 + oy + (f + 2) * esc, esc, esc);
      if (marca) for (let f = 0; f < 2; f++) for (let k = 0; k < 5; k++) if (marca[f][k] === '#') g.fillRect(cx + k * esc, y0 + oy + f * esc, esc, esc);
      if (cedilla) { g.fillRect(cx + 2 * esc, y0 + oy + 9 * esc, esc, esc); g.fillRect(cx + 1 * esc, y0 + oy + 10 * esc, esc * 2, esc); }
      cx += (filas[0].length + 1) * esc;
    }
  };
  if (borde) for (const [ox, oy] of [[-esc, 0], [esc, 0], [0, -esc], [0, esc], [-esc, -esc], [esc, -esc], [-esc, esc], [esc, esc]]) pintar(borde, ox, oy);
  if (sombra) pintar(sombra, 0, esc);
  pintar(color, 0, 0);
  return w;
}

// Parte un texto en renglones que entren en `ancho` px.
export function partir(txt, ancho, esc = 1) {
  const palabras = String(txt).split(/\s+/), lineas = [];
  let l = '';
  for (const p of palabras) {
    const prueba = l ? l + ' ' + p : p;
    if (anchoTexto(prueba, esc) > ancho && l) { lineas.push(l); l = p; } else l = prueba;
  }
  if (l) lineas.push(l);
  return lineas;
}
