/** Una letra a mano: el dibujo de MANO, con su baile propio (renglón, inclinación) según la variante. */
function glifoMano(ch, variante) {
  const k = ch + variante;
  if (_glifosM[k]) return _glifosM[k];
  const m = MARCAS[ch], base = m ? m[0] : ch, filas = MANO[base] || MANO["?"], r = mulberry(hashTexto("mano" + k));
  // el baile: la letra sube o baja un píxel, y a veces se inclina (la mitad de arriba corrida)
  const angosta = filas[0].length <= 2;
  const baja = r() < 0.3 ? 1 : r() < 0.2 ? -1 : 0, inclina = !angosta && r() < 0.35 ? (r() < 0.5 ? -1 : 1) : 0;
  // la inclinación corre la mitad de arriba; la letra se hace un píxel más ancha para no pisar a la vecina
  const corre = inclina < 0 ? 1 : 0, px = [];
  filas.forEach((f, y) => { const dx = inclina && y < 4 ? inclina : 0; for (let x = 0; x < f.length; x++) if (f[x] === "#") px.push([x + dx + corre + 1, y]); });
  const w = filas[0].length + 2 + (inclina ? 1 : 0);
  return (_glifosM[k] = { w, px, baja, marca: m ? m[1] : null, ancho: filas[0].length + 1 + (inclina ? 1 : 0) });
}
/** Texto a mano (marcador oscuro sobre papel). o: {tinta, borde} */
function manoSpr(str, o = {}) {
  str = String(str).toUpperCase();
  const tinta = o.tinta || "#2b2326";
  return hornear(`mano|${str}|${tinta}`, () => {
    const letras = [...str].map((ch, i) => (ch === " " ? null : glifoMano(ch, i % 3)));
    let W = 0; letras.forEach((l) => { W += l ? l.ancho + 1 : 5; });
    const arriba = 4, H = 12 + arriba, p = new Pix(W + 4, H);
    let x = 2;
    letras.forEach((l) => {
      if (!l) { x += 5; return; }
      for (const [px, py] of l.px) p.p(x + px, arriba + py + l.baja, tinta);
      if (l.marca === "´") { const cx0 = x + Math.round(l.w / 2); p.p(cx0, arriba - 1, tinta); p.p(cx0 + 1, arriba - 1, tinta); p.p(cx0 + 1, arriba - 2, tinta); p.p(cx0 + 2, arriba - 2, tinta); }
      if (l.marca === "~") { const cx0 = x + Math.round(l.w / 2) - 2; for (const [dx, dy] of [[0, 0], [1, -1], [2, -1], [3, 0], [4, 0], [5, -1]]) p.p(cx0 + dx, arriba - 1 + dy, tinta); }
      if (l.marca === "¨") { const cx0 = x + Math.round(l.w / 2); p.p(cx0 - 2, arriba - 1, tinta); p.p(cx0 + 2, arriba - 1, tinta); }
      x += l.ancho + 1;
    });
    // el papel se chupa un poco la tinta: un borde gris muy suave alrededor del trazo
    if (o.borde ?? true) p.contorno("rgba(60,48,50,0.28)", false);
    return p.canvas();
  });
}

