const ALTO_BLOQUE = 8;

/** ¿Dónde se gasta cada letra? Un par de mordiscos por glifo, siempre los mismos (semilla por letra). */
function gastar(filas, ch) {
  const r = mulberry(hashTexto("gasta" + ch)), m = filas.map((f) => [...f]);
  const h = m.length, w = m[0].length, lleno = (x, y) => x >= 0 && y >= 0 && x < w && y < h && m[y][x] === "#";
  const esquinas = [];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (!lleno(x, y)) continue;
    // esquina de afuera: vacío arriba o abajo, y vacío a un costado, pero con el trazo sano al lado
    const vert = !lleno(x, y - 1) || !lleno(x, y + 1), hor = !lleno(x - 1, y) || !lleno(x + 1, y);
    if (vert && hor && (lleno(x + 1, y) || lleno(x - 1, y)) && (lleno(x, y + 1) || lleno(x, y - 1))) esquinas.push([x, y]);
  }
  const n = w > 3 ? (r() < 0.55 ? 1 : 0) + (r() < 0.2 ? 1 : 0) : 0;
  for (let i = 0; i < n && esquinas.length; i++) { const [x, y] = esquinas.splice(Math.floor(r() * esquinas.length), 1)[0]; m[y][x] = "g"; }   // "g" = gastado (gris, no hueco)
  return m.map((f) => f.join(""));
}
const _glifosB = {};
function glifoBloque(ch) {
  if (_glifosB[ch]) return _glifosB[ch];
  const base = BLOQUE[ch] || BLOQUE["?"];
  return (_glifosB[ch] = { w: base[0].length, filas: gastar(base, ch) });
}

// ── dibujar texto en las tres letras ──
function _medir(str, ancho, esp) { let w = 0; for (const ch of str) w += ancho(ch) + esp; return Math.max(1, w - esp); }

/** Letra de bloque: blanca (o con degradé), gastada, contorno negro y sombra. o: {grad, sombra, escala} */
function bloqueSpr(str, o = {}) {
  str = String(str).toUpperCase();
  const clave = `blq|${str}|${o.grad || "hueso"}|${o.sombra ?? 1}`;
  return hornear(clave, () => {
    const esp = 1, arriba = 3, W = _medir(str, (ch) => glifoBloque(MARCAS[ch] ? MARCAS[ch][0] : ch).w, esp);
    const p = new Pix(W + 4, ALTO_BLOQUE + arriba + 4);
    const R = o.grad === "rojo" ? ["#ffd6c8", "#ff8f74", "#f0553d", "#c8302a", "#8e1a19"] : o.grad === "oro" ? ["#fff4c4", "#ffe08a", "#f5c24a", "#d8962a", "#9c6014"] : o.grad === "espora" ? ["#f2fffb", "#c9f5e8", "#8fe0cc", "#56b3a3", "#2c716a"] : ["#ffffff", "#f6f2ea", "#ece6da", "#d6cfc1", "#b3aa99"];
    let x = 2;
    for (const ch of str) {
      const m = MARCAS[ch], gl = glifoBloque(m ? m[0] : ch);
      gl.filas.forEach((f, y) => {
        for (let i = 0; i < f.length; i++) {
          if (f[i] === ".") continue;
          // degradé por fila, y lo gastado un tono más apagado
          const t = y / (ALTO_BLOQUE - 1), k = f[i] === "g" ? 4 : lim(Math.floor(t * 3.2 + bayer(x + i, y) * 0.8), 0, 3);
          p.p(x + i, arriba + 2 + y, R[k]);
        }
      });
      if (m) {
        const c0 = x + Math.floor(gl.w / 2) - 1, y0 = arriba;
        if (m[1] === "´") { p.p(c0 + 1, y0, R[0]); p.p(c0 + 2, y0, R[0]); p.p(c0 + 2, y0 - 1, R[0]); p.p(c0 + 3, y0 - 1, R[0]); }
        if (m[1] === "~") for (const [dx, dy] of [[-1, 0], [0, -1], [1, -1], [2, 0], [3, 0], [4, -1]]) p.p(c0 + dx, y0 + dy, R[0]);
        if (m[1] === "¨") { p.p(c0, y0, R[0]); p.p(c0 - 1, y0, R[0]); p.p(c0 + 3, y0, R[0]); p.p(c0 + 4, y0, R[0]); }
      }
      x += gl.w + esp;
    }
    p.contorno(PAL.tinta, true);
    let c = p.canvas();
    if (o.sombra ?? 1) {   // la sombra dura, un píxel abajo a la derecha (como el original)
      const s = lienzoNuevo(c.width + 1, c.height + 1), g = s.getContext("2d");
      g.drawImage(tinte(c, PAL.tinta), 1, 1); g.drawImage(c, 0, 0);
      c = s;
    }
    return c;
  });
}

