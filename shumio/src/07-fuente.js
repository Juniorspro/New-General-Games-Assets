/** Hornea un texto: relleno con degradé por fila, contorno y sombra. o: {grad, contorno, sombra, escala} */
function textoSpr(str, o = {}) {
  str = String(str).toUpperCase();
  const clave = `tx|${str}|${o.grad || "blanco"}|${o.contorno ?? 1}|${o.sombra ?? 1}`;
  return hornear(clave, () => {
    const esp = 1, alto = 7, arriba = 3;
    let w = 0;
    for (const ch of str) { const base = MARCAS[ch] ? MARCAS[ch][0] : ch; w += glifo(base).w + esp; }
    w = Math.max(1, w - esp);
    const p = new Pix(w + 4, alto + arriba + 4), grad = GRADIENTES[o.grad || "blanco"];
    let x = 2;
    for (const ch of str) {
      const m = MARCAS[ch], base = m ? m[0] : ch, gl = glifo(base);
      gl.filas.forEach((f, y) => { for (let i = 0; i < f.length; i++) if (f[i] === "#") p.p(x + i, arriba + 2 + y, grad[y]); });
      if (m) {
        const cx0 = x + Math.floor(gl.w / 2);
        if (m[1] === "´") { p.p(cx0, arriba, grad[0]); p.p(cx0 + 1, arriba - 1, grad[0]); }
        if (m[1] === "~") { p.p(cx0 - 2, arriba, grad[0]); p.p(cx0 - 1, arriba - 1, grad[0]); p.p(cx0, arriba, grad[0]); p.p(cx0 + 1, arriba - 1, grad[0]); }
        if (m[1] === "¨") { p.p(cx0 - 1, arriba, grad[0]); p.p(cx0 + 1, arriba, grad[0]); }
      }
      x += gl.w + esp;
    }
    if (o.contorno ?? 1) p.contorno(PAL.tinta, true);
    let c = p.canvas();
    if (o.sombra ?? 1) {
      const s = lienzoNuevo(c.width + 1, c.height + 1), g = s.getContext("2d");
      g.globalAlpha = 0.55; g.drawImage(blanco(c), 1, 1); g.globalCompositeOperation = "source-in"; g.fillStyle = "#000"; g.fillRect(0, 0, s.width, s.height);
      g.globalCompositeOperation = "source-over"; g.globalAlpha = 1; g.drawImage(c, 0, 0);
      c = s;
    }
    return c;
  });
}
