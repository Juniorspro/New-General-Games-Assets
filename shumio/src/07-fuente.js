// tildes y Ñ: la letra base con la marca encima (3 filas de aire arriba en el lienzo)
const MARCAS = { "Á": ["A", "´"], "É": ["E", "´"], "Í": ["I", "´"], "Ó": ["O", "´"], "Ú": ["U", "´"], "Ñ": ["N", "~"], "Ü": ["U", "¨"] };
const _glifo = {};
function glifo(ch) {
  if (_glifo[ch]) return _glifo[ch];
  const g = GLIFOS[ch] || GLIFOS["?"];
  const filas = g.split("|");
  return (_glifo[ch] = { w: filas[0].length, filas });
}

